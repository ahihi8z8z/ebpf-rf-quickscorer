#!/usr/bin/env python3
"""Emit params.h for hara_ref.c from Hara's shipped model files (no modification):
    python3 gen_params.py hara_src > params.h
NN: nn-filter/mlp_params.json (binary 12-16-16-2, the in-kernel XDP model).
DT: dt-filter/runs/{childrenLeft,childrenRight,feature,threshold,value}."""
import json, os, sys

src = sys.argv[1]
nn = json.load(open(os.path.join(src, 'nn-filter', 'mlp_params.json')))
out = ['/* generated by gen_params.py from Hara shipped parameters; do not edit */']
for k, v in nn.items():
    ty = 'int64_t' if k in ('data_min', 'data_scale') else 'int'
    out.append(f'static const {ty} P_{k}[{len(v)}] = {{{", ".join(map(str, v))}}};')
for k in ('childrenLeft', 'childrenRight', 'feature', 'threshold', 'value'):
    v = json.load(open(os.path.join(src, 'dt-filter', 'runs', k)))
    out.append(f'static const int64_t DT_{k}[{len(v)}] = {{{", ".join(str(int(x)) for x in v)}}};')
out.append(f'#define DT_NODES {len(v)}')
print('\n'.join(out))
